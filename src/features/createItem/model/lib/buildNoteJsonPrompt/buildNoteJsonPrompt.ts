export interface NotePromptContext {
  existingTags: readonly string[];
  projectTitles: readonly string[];
}

const formatList = (items: readonly string[]): string =>
  items.slice(0, CONTEXT_LIST_LIMIT).join(', ');

export const buildNoteContext = ({ existingTags, projectTitles }: NotePromptContext): string[] => [
      ...CONTEXT,
      ...(existingTags.length > 0
        ? [
            `Наявні теги користувача: ${formatList(existingTags)}. Спершу добирай теги з цього списку (пиши їх точно так само); нові додавай лише коли жоден не підходить.`,
          ]
        : []),
      ...(projectTitles.length > 0
        ? [`Наявні проєкти користувача: ${formatList(projectTitles)}.`]
        : []),
];

export const buildNoteJsonPrompt = (context: NotePromptContext): string =>
  buildJsonPrompt({
    subject: 'нотатки',
    fields: NOTE_JSON_FIELDS,
    example: NOTE_JSON_EXAMPLE,
    rules: NOTE_JSON_RULES,
    context: buildNoteContext(context),
  });